import assert from 'node:assert/strict';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {chromium} from 'playwright-core';
import path from 'node:path';
const base=process.env.ATLAS_OWNER_TEST_URL??'http://127.0.0.1:4310';
if(new URL(base).hostname!=='127.0.0.1')throw Error('Owner acceptance requires exact loopback');
const out=path.resolve('../.ai/raw/owner-primary-strategy-20261027/browser');
await mkdir(out,{recursive:true,mode:0o700});
const browser=await chromium.launch({headless:true,
 executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const context=await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block'});
const page=await context.newPage(),errors=[],writes=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(new URL(r.url()).origin===base&&r.method()!=='GET')writes.push(r.method());});
const evidence={};
try{
 const account=await (await context.request.get(base+'/api/scalpstorm-owner')).json();
 assert.equal(account.mode,'FORWARD');assert.equal(account.ledgerVerified,true);
 assert.equal(account.realOrdersEnabled,false);assert.equal(account.actualCapitalINR,0);
 await page.goto(base+'/#nse-paper');await page.getByRole('heading',{name:'ScalpStorm X.'}).waitFor();
 await page.getByText('Account equity',{exact:true}).waitFor();
 assert.ok(await page.getByText('9:40',{exact:true}).count());
 assert.ok(await page.getByText('3:15',{exact:true}).count());
 assert.equal(await page.getByText('Start 5 forward paper trials',{exact:true}).count(),0);
 await page.screenshot({path:path.join(out,'strategy-desktop.png'),fullPage:true});
 evidence.account={status:account.status,fills:account.fills,ledgerVerified:true};
 await page.getByRole('button',{name:'10Y',exact:true}).click();
 await page.getByRole('img',{name:/Nifty 50 actual source closing prices, 10Y/}).waitFor();
 await page.getByRole('button',{name:'IPO Intelligence',exact:true}).click();
 await page.locator('.ipo-row').first().waitFor();
 const rows=await page.locator('.ipo-row').count();assert.ok(rows>0);
 await page.locator('.ipo-row').first().click();await page.getByRole('region',{name:'IPO issue details'}).waitFor();
 assert.equal(await page.getByRole('button',{name:/Refresh/i}).count(),0);
 const company=await page.locator('.ipo-detail h2').innerText();
 await page.clock.install();
 await page.route('**/api/ipo-feed',r=>r.abort());
 await page.route('**/ipo-feed.json',r=>r.abort());
 await page.clock.fastForward(61_000);
 assert.equal(await page.locator('.ipo-row').count(),rows);
 assert.equal(await page.locator('.ipo-detail h2').innerText(),company);
 assert.equal(await page.getByText('Checking sources…',{exact:true}).count(),0);
 await page.screenshot({path:path.join(out,'ipo-retained-on-source-failure.png'),fullPage:true});
 evidence.ipo={rows,retainedOnRefreshFailure:true,selectionPreserved:true,manualRefreshButtons:0};
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'ipo-mobile.png'),fullPage:true});
 const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert.ok(width.scroll<=width.viewport+1,JSON.stringify(width));
 evidence.mobile=width;
 await page.getByRole('button',{name:'Open menu',exact:true}).click();
 await page.getByRole('button',{name:'ScalpStorm X',exact:true}).click();
 await page.getByRole('heading',{name:'ScalpStorm X.'}).waitFor();
 await page.screenshot({path:path.join(out,'strategy-mobile.png'),fullPage:true});
 assert.deepEqual(writes,[]);assert.deepEqual(errors,[]);
 evidence.success=true;
 await writeFile(path.join(out,'acceptance.json'),JSON.stringify(evidence,null,2),{mode:0o600});
 console.log(JSON.stringify(evidence));
}finally{await context.close();await browser.close();}
